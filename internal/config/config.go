// Verify verify
func (cfg *Config) Verify() {
	if cfg.JWTRandom {
		log.Warn("The authentication will fail the next time you start the server!")
		log.Warnf("%s was not set! The following was autogenerated", envJWTSecretKey)
		log.Warnf("%s=%X", envJWTSecretKey, cfg.JWTSecretKey)
	}

	if !cfg.HTTPSCookie {
		log.Warnln(envHTTPSCookie + " is not set, use only when not using https!")
	}

	if cfg.SMTPConfig == nil {
		log.Warnln("smtp not configured, no emails will be sent")
	}

	if cfg.HWRApplicationKey == "" {
		log.Info("if you want HWR, provide the myScript applicationKey in: " + envHwrApplicationKey)
	}
	if cfg.HWRHmac == "" {
		log.Info("provide the myScript hmac in: " + envHwrHmac)
	}

	if cfg.Certificate.Certificate == nil {
		log.Info("For HTTPS, provide " + envTLSCert + " and " + envTLSKey)
	} else {
		log.Info("MQTT will use provided TLS certificate")
	}

	if len(cfg.ICEServers) > 0 {
		log.Infof("WebRTC configured with %d ICE server(s)", len(cfg.ICEServers))
	} else {
		log.Info("No ICE servers configured - screenshare will only work on local networks")
	}
}

// FromEnv config from environment values
func FromEnv() *Config {
	var err error
	var dataDir string
	data := os.Getenv(envDataDir)
	if data != "" {
		dataDir = data
	} else {
		dataDir, err = filepath.Abs(DefaultDataDir)
		if err != nil {
			log.Fatal("DataDir: ", err)
		}
	}

	port := os.Getenv(envPort)
	if port == "" {
		port = DefaultPort
	}

	jwtGenerated := false
	jwtSecretKey := []byte(os.Getenv(envJWTSecretKey))
	if len(jwtSecretKey) == 0 {
		jwtSecretKey = make([]byte, 32)
		_, err := rand.Read(jwtSecretKey)
		if err != nil {
			log.Fatal(err)
		}
		jwtGenerated = true
	}
	dk := pbkdf2.Key(jwtSecretKey, []byte("todo some salt"), 10000, 32, sha256.New)

	var cert tls.Certificate
	certPath := os.Getenv(envTLSCert)
	keyPath := os.Getenv(envTLSKey)
	if certPath != "" && keyPath != "" {

		cert, err = tls.LoadX509KeyPair(certPath, keyPath)
		if err != nil {
			log.Fatal("unable to load certificate:", err)
		}
	}
	openRegistration, _ := strconv.ParseBool(os.Getenv(envRegistrationOpen))
	httpsCookie, _ := strconv.ParseBool(os.Getenv(envHTTPSCookie))

	cloudHost := DefaultHost
	uploadURL := os.Getenv(EnvStorageURL)
	if uploadURL == "" {
		//it will go through the local proxy
		uploadURL = "https://" + DefaultHost
	} else {
		u, err := url.Parse(uploadURL)
		if err != nil || (u.Scheme != "http" && u.Scheme != "https") || u.Host == "" {
			log.Fatalf("%s '%s' cannot be parsed, or missing scheme (http|https) %v", EnvStorageURL, uploadURL, err)
		}
		if u.Port() != "" {
			log.Warn(EnvStorageURL, " >= 3.15 doesnt support :port, only https, sync will fail!")
		}
		if u.Scheme != "https" {
			log.Warn(EnvStorageURL, " >= 3.15 only https is supported, sync fill fail!")
		}
		cloudHost = u.Host
	}

	// smtp
	var smtpCfg *email.SMTPConfig
	servername := os.Getenv(envSMTPServer)

	if servername != "" {
		inSecureTLS, _ := strconv.ParseBool(os.Getenv(envSMTPInsecureTLS))
		noTLS, _ := strconv.ParseBool(os.Getenv(envSMTPNoTLS))
		startTLS, _ := strconv.ParseBool(os.Getenv(envSMTPStartTLS))
		smtpCfg = &email.SMTPConfig{
			Server:      servername,
			Username:    os.Getenv(envSMTPUsername),
			Password:    os.Getenv(envSMTPPassword),
			Helo:        os.Getenv(envSMTPHelo),
			NoTLS:       noTLS,
			StartTLS:    startTLS,
			InsecureTLS: inSecureTLS,
		}
		fromOverride := os.Getenv(envSMTPFrom)
		if fromOverride != "" {
			fromAddress, err := mail.ParseAddress(os.Getenv(envSMTPFrom))
			if err != nil {
				log.Warn(envSMTPFrom, " can't parse address: ", fromAddress, err)
			} else {
				smtpCfg.FromOverride = fromAddress
			}
		}
	}

	trustProxy, _ := strconv.ParseBool(os.Getenv(envTrustProxy))

	mqttPort := os.Getenv(envMQTTPort)
	if mqttPort == "" {
		mqttPort = "8883"
	}

	var iceServers []interface{}
	iceServersJSON := os.Getenv(envICEServers)
	if iceServersJSON != "" {
		err := json.Unmarshal([]byte(iceServersJSON), &iceServers)
		if err != nil {
			log.Warnf("Failed to parse %s: %v", envICEServers, err)
			iceServers = nil
		}
	}
	if len(iceServers) == 0 {
		iceServers = []interface{}{
			map[string]string{"url": "stun:stun.l.google.com:19302", "username": "", "credential": ""},
		}
	}
	iceServers = normalizeICEServers(iceServers)

	hashSchemaVersion := os.Getenv(envHashSchemaVersion)
	if hashSchemaVersion == "" {
		hashSchemaVersion = "3"
	} else if hashSchemaVersion != "3" && hashSchemaVersion != "4" {
		log.Fatalf("%s must be either '3' or '4', got: %s", envHashSchemaVersion, hashSchemaVersion)
	}

	cfg := Config{
		Render:            renderFromEnv(),
		Port:              port,
		StorageURL:        uploadURL,
		CloudHost:         cloudHost,
		DataDir:           dataDir,
		JWTSecretKey:      dk,
		JWTRandom:         jwtGenerated,
		Certificate:       cert,
		RegistrationOpen:  openRegistration,
		SMTPConfig:        smtpCfg,
		HWRApplicationKey: os.Getenv(envHwrApplicationKey),
		HWRHmac:           os.Getenv(envHwrHmac),
		HWRLangOverride:   os.Getenv(envHwrLangOverride),
		HWRHost:           os.Getenv(envHwrHost),
		HTTPSCookie:       httpsCookie,
		TrustProxy:        trustProxy,
		MQTTPort:          mqttPort,
		ICEServers:        iceServers,
		HashSchemaVersion: hashSchemaVersion,
	}
	return &cfg
}

// renderFromEnv reads the RMLINES_* variables. Invalid values are logged and
// ignored.
func renderFromEnv() RenderConfig {
	var r RenderConfig
	r.Disable = envBool(envRmlinesDisable, false)
	r.NoClip = !envBool(envRmlinesClip, true)
	if v := os.Getenv(envRmlinesWorkers); v != "" {
		if n, err := strconv.Atoi(v); err == nil && n >= 1 && n <= 64 {
			r.Workers = n
		} else {
			log.Warnf("%s=%q ignored: want a number of workers from 1 to 64", envRmlinesWorkers, v)
		}
	}
	if v := os.Getenv(envRmlinesScale); v != "" {
		if f, err := strconv.ParseFloat(v, 64); err == nil && f > 0 && f <= 16 {
			r.Scale = f
		} else {
			log.Warnf("%s=%q ignored: want a number in (0, 16]", envRmlinesScale, v)
		}
	}
	if v := os.Getenv(envRmlinesSupersample); v != "" {
		if n, err := strconv.Atoi(v); err == nil && n >= 1 && n <= 8 {
			r.Supersample = n
		} else {
			log.Warnf("%s=%q ignored: want 1 to 8", envRmlinesSupersample, v)
		}
	}
	if v := os.Getenv(envRmlinesTimeout); v != "" {
		d, err := time.ParseDuration(v)
		if err != nil {
			if secs, err2 := strconv.Atoi(v); err2 == nil {
				d, err = time.Duration(secs)*time.Second, nil
			}
		}
		if err == nil && d > 0 {
			r.Timeout = d
		} else {
			log.Warnf("%s=%q ignored: want a duration such as 30s", envRmlinesTimeout, v)
		}
	}
	if v := os.Getenv(envRmlinesPtPerPx); v != "" {
		if f, ok := parseRatio(v); ok && f > 0.05 && f < 5 {
			r.PtPerPx = f
		} else {
			log.Warnf("%s=%q ignored: want points per page unit, e.g. 0.3172 or 72/227", envRmlinesPtPerPx, v)
		}
	}
	return r
}

func envBool(name string, def bool) bool {
	v := os.Getenv(name)
	if v == "" {
		return def
	}
	b, err := strconv.ParseBool(v)
	if err != nil {
		log.Warnf("%s=%q ignored: want true or false", name, v)
		return def
	}
	return b
}

// parseRatio parses "0.3172" or "72/227".
func parseRatio(s string) (float64, bool) {
	if a, b, ok := strings.Cut(s, "/"); ok {
		n, err1 := strconv.ParseFloat(strings.TrimSpace(a), 64)
		d, err2 := strconv.ParseFloat(strings.TrimSpace(b), 64)
		if err1 != nil || err2 != nil || d == 0 {
			return 0, false
		}
		return n / d, true
	}
	f, err := strconv.ParseFloat(strings.TrimSpace(s), 64)
	return f, err == nil
}

// normalizeICEServers expands "urls" arrays into singular "url" entries; xochitl rejects anything else
func normalizeICEServers(servers []interface{}) []interface{} {
	normalized := make([]interface{}, 0, len(servers))
	for _, s := range servers {
		m, ok := toStringMap(s)
		if !ok {
			normalized = append(normalized, s)
			continue
		}
		_, hasURL := m["url"]
		_, hasURLs := m["urls"]
		urls := collectICEURLs(m)
		if len(urls) == 0 {
			if !hasURL && !hasURLs {
				normalized = append(normalized, s)
			}
			continue
		}
		for _, u := range urls {
			entry := map[string]interface{}{"url": u}
			for k, v := range m {
				if k == "url" || k == "urls" {
					continue
				}
				entry[k] = v
			}
			normalized = append(normalized, entry)
		}
	}
	return normalized
}

func toStringMap(v interface{}) (map[string]interface{}, bool) {
	switch t := v.(type) {
	case map[string]interface{}:
		return t, true
	case map[string]string:
		m := make(map[string]interface{}, len(t))
		for k, val := range t {
			m[k] = val
		}
		return m, true
	default:
		return nil, false
	}
}

func collectICEURLs(m map[string]interface{}) []string {
	var urls []string
	add := func(v interface{}) {
		switch t := v.(type) {
		case string:
			if t != "" {
				urls = append(urls, t)
			}
		case []interface{}:
			for _, item := range t {
				if str, ok := item.(string); ok && str != "" {
					urls = append(urls, str)
				}
			}
		}
	}
	add(m["url"])
	add(m["urls"])
	return urls
}

